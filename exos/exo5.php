<?php
//Exercice 5 : Boucle `for`

for ($i = 1; $i <= 10; $i++) {
    echo "<pre>";
    echo $i . "\n";
    echo "<pre>";
}

//for (initialisation; condition; incrémentation) :
//$i = 1 : on démarre le compteur à 1.
//$i <= 10 : la boucle continue tant que $i est inférieur ou égal à 10.
//$i++ : à chaque tour, $i augmente de 1 (équivalent à $i = $i + 1).